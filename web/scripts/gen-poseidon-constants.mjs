// Extracts Poseidon2 BN254 round constants (t=2 and t=3) straight from the circom
// source of truth (circom/poseidon2/poseidon2_const.circom) into a TS module, so the
// browser prover's permutation shares byte-identical constants with the circuits and
// the on-chain Soroban host. Run: `node scripts/gen-poseidon-constants.mjs`.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(here, "../../circom/poseidon2/poseidon2_const.circom");
const OUT = resolve(here, "../lib/prove/poseidon2-constants.ts");

const src = readFileSync(SRC, "utf8");

// Grab the body of a `function NAME(t) { ... }` block.
function fnBody(name) {
  const i = src.indexOf(`function ${name}(t)`);
  if (i < 0) throw new Error(`function ${name} not found`);
  let depth = 0, start = -1;
  for (let j = i; j < src.length; j++) {
    if (src[j] === "{") { if (depth++ === 0) start = j + 1; }
    else if (src[j] === "}") { if (--depth === 0) return src.slice(start, j); }
  }
  throw new Error(`unbalanced braces in ${name}`);
}

// The `if (t==N) { ... }` sub-block within a function body.
function tBlock(body, n) {
  const marker = `t==${n}`;
  const i = body.indexOf(marker);
  if (i < 0) throw new Error(`t==${n} not found`);
  let depth = 0, start = -1;
  for (let j = body.indexOf("{", i); j < body.length; j++) {
    if (body[j] === "{") { if (depth++ === 0) start = j + 1; }
    else if (body[j] === "}") { if (--depth === 0) return body.slice(start, j); }
  }
  throw new Error(`unbalanced braces for t==${n}`);
}

const hexes = (s) => (s.match(/0x[0-9a-fA-F]+/g) ?? []).map((h) => BigInt(h));
const chunk = (arr, k) => { const o = []; for (let i = 0; i < arr.length; i += k) o.push(arr.slice(i, i + k)); return o; };

const partial = fnBody("POSEIDON_PARTIAL_ROUNDS");
const full = fnBody("POSEIDON_FULL_ROUNDS");
const diag = fnBody("POSEIDON_INTERNAL_MAT_DIAG");

const RC_PARTIAL_T2 = hexes(tBlock(partial, 2));
const RC_PARTIAL_T3 = hexes(tBlock(partial, 3));
const RC_FULL_T2 = chunk(hexes(tBlock(full, 2)), 2);
const RC_FULL_T3 = chunk(hexes(tBlock(full, 3)), 3);
const DIAG_T2 = hexes(tBlock(diag, 2));
const DIAG_T3 = hexes(tBlock(diag, 3));

// Shape assertions — the permutation is 4+56+4 rounds; wrong counts = silent hash drift.
const check = (name, got, want) => { if (got !== want) throw new Error(`${name}: expected ${want}, got ${got}`); };
check("RC_PARTIAL_T2", RC_PARTIAL_T2.length, 56);
check("RC_PARTIAL_T3", RC_PARTIAL_T3.length, 56);
check("RC_FULL_T2 rows", RC_FULL_T2.length, 8);
check("RC_FULL_T3 rows", RC_FULL_T3.length, 8);
RC_FULL_T2.forEach((r, i) => check(`RC_FULL_T2[${i}]`, r.length, 2));
RC_FULL_T3.forEach((r, i) => check(`RC_FULL_T3[${i}]`, r.length, 3));
check("DIAG_T2", DIAG_T2.length, 2);
check("DIAG_T3", DIAG_T3.length, 3);

const bn = (v) => `${v}n`;
const arr1 = (a) => `[\n  ${a.map(bn).join(",\n  ")},\n]`;
const arr2 = (a) => `[\n  ${a.map((r) => `[${r.map(bn).join(", ")}]`).join(",\n  ")},\n]`;

const out = `// AUTO-GENERATED by scripts/gen-poseidon-constants.mjs from
// circom/poseidon2/poseidon2_const.circom — DO NOT EDIT BY HAND.
// Horizen Poseidon2 BN254 round constants for t=2 (compress) and t=3 (hash2).

/** Partial-round constants (56 scalars), t=2. */
export const RC_PARTIAL_T2: bigint[] = ${arr1(RC_PARTIAL_T2)};

/** Partial-round constants (56 scalars), t=3. */
export const RC_PARTIAL_T3: bigint[] = ${arr1(RC_PARTIAL_T3)};

/** Full-round constants (8 rounds x 2), t=2. */
export const RC_FULL_T2: bigint[][] = ${arr2(RC_FULL_T2)};

/** Full-round constants (8 rounds x 3), t=3. */
export const RC_FULL_T3: bigint[][] = ${arr2(RC_FULL_T3)};

/** Internal-matrix diagonal, t=2. */
export const DIAG_T2: bigint[] = [${DIAG_T2.map(bn).join(", ")}];

/** Internal-matrix diagonal, t=3. */
export const DIAG_T3: bigint[] = [${DIAG_T3.map(bn).join(", ")}];
`;

writeFileSync(OUT, out);
console.log(`wrote ${OUT}`);
console.log(`  RC_PARTIAL_T2=${RC_PARTIAL_T2.length} RC_PARTIAL_T3=${RC_PARTIAL_T3.length}`);
console.log(`  RC_FULL_T2=${RC_FULL_T2.length}x2 RC_FULL_T3=${RC_FULL_T3.length}x3`);
console.log(`  DIAG_T2=[${DIAG_T2}] DIAG_T3=[${DIAG_T3}]`);
