// Generate contracts/veil-verifier/src/fixtures.rs from the committed vkeys (keys/*.vk.json) and
// per-circuit proofs (/tmp/<c>_proof.json, /tmp/<c>_public.json — produce them with:
//   node lock_test_js/generate_witness.js lock_test_js/lock_test.wasm lock_input.json /tmp/lock.wtns
//   snarkjs groth16 prove lock.zkey /tmp/lock.wtns /tmp/lock_proof.json /tmp/lock_public.json
//   node release_repaid_test_js/generate_witness.js ... /tmp/release_repaid.wtns
//   snarkjs groth16 prove release_repaid.zkey /tmp/release_repaid.wtns /tmp/release_repaid_proof.json /tmp/release_repaid_public.json
//
// Soroban BN254 encoding (must match contracts/veil-verifier/build.rs):
//   G1 = x||y (64B BE);  G2 = x.c1||x.c0||y.c1||y.c0 (128B BE);  Fr = 32B BE.
//
// PRESERVE POLICY: BORROW, UNLOCK, SEIZE are read verbatim from the existing fixtures.rs.
// Only LOCK and RELEASE_REPAID are regenerated from /tmp proofs + committed VKs.
//
// Run: node circom/gen_fixtures.js  (from repo root)  OR  node gen_fixtures.js  (from circom/)
const fs = require("fs");
const path = require("path");

const fq32 = (dec) => BigInt(dec).toString(16).padStart(64, "0").match(/../g).map((b) => "0x" + b).join(",");
const g1 = (pt) => `[${fq32(pt[0])},${fq32(pt[1])}]`;
const g2 = (pt) => `[${fq32(pt[0][1])},${fq32(pt[0][0])},${fq32(pt[1][1])},${fq32(pt[1][0])}]`;

// Determine paths relative to this script's directory (circom/)
const scriptDir = __dirname;
const fixturesPath = path.resolve(scriptDir, "../contracts/veil-verifier/src/fixtures.rs");

// --- Read existing fixtures.rs and extract verbatim blocks for preserved circuits ---
const existing = fs.readFileSync(fixturesPath, "utf8");

function extractConst(src, name) {
  // Match from "pub const NAME: Fx = Fx {" to the closing "};\n" (greedy-safe: find last }; after the opening)
  const startToken = `pub const ${name}: Fx = Fx {`;
  const startIdx = src.indexOf(startToken);
  if (startIdx === -1) throw new Error(`Cannot find ${name} block in existing fixtures.rs`);
  // Find the closing "};\n" — the block uses one nesting level so the first "\n};\n" after the opening is the end.
  const endToken = "\n};\n";
  const endIdx = src.indexOf(endToken, startIdx);
  if (endIdx === -1) throw new Error(`Cannot find closing }; for ${name} in fixtures.rs`);
  return src.slice(startIdx, endIdx + endToken.length);
}

const BORROW_BLOCK = extractConst(existing, "BORROW");
const UNLOCK_BLOCK = extractConst(existing, "UNLOCK");
const SEIZE_BLOCK  = extractConst(existing, "SEIZE");

// --- Regenerate LOCK and RELEASE_REPAID from disk VKs + /tmp proofs ---
function genConst(name) {
  const vkPath = path.join(scriptDir, `keys/${name}.vk.json`);
  const prPath = `/tmp/${name}_proof.json`;
  const pubPath = `/tmp/${name}_public.json`;
  const vk  = JSON.parse(fs.readFileSync(vkPath));
  const pr  = JSON.parse(fs.readFileSync(prPath));
  const pub = JSON.parse(fs.readFileSync(pubPath));
  const ic = vk.IC.map(g1).join(",\n    ");
  const publics = pub.map((x) => `[${fq32(x)}]`).join(",\n    ");
  let block = `pub const ${name.toUpperCase()}: Fx = Fx {\n`;
  block += `  vk_alpha: ${g1(vk.vk_alpha_1)},\n  vk_beta: ${g2(vk.vk_beta_2)},\n  vk_gamma: ${g2(vk.vk_gamma_2)},\n  vk_delta: ${g2(vk.vk_delta_2)},\n`;
  block += `  vk_ic: &[\n    ${ic}\n  ],\n`;
  block += `  proof_a: ${g1(pr.pi_a)},\n  proof_b: ${g2(pr.pi_b)},\n  proof_c: ${g1(pr.pi_c)},\n`;
  block += `  public: &[\n    ${publics}\n  ],\n};\n`;
  return block;
}

const LOCK_BLOCK         = genConst("lock");
const RELEASE_REPAID_BLOCK = genConst("release_repaid");

// --- Assemble output: BORROW, LOCK, UNLOCK, SEIZE, RELEASE_REPAID ---
let out = "// @generated by circom/gen_fixtures.js from keys/*.vk.json + /tmp/<c>_{proof,public}.json — do not edit.\n";
out += "// Soroban BN254 encoding: G1 = x||y (64B BE); G2 = x.c1||x.c0||y.c1||y.c0 (128B BE); Fr = 32B BE.\n\n";
out += "pub struct Fx {\n  pub vk_alpha:[u8;64], pub vk_beta:[u8;128], pub vk_gamma:[u8;128], pub vk_delta:[u8;128],\n  pub vk_ic:&'static[[u8;64]], pub proof_a:[u8;64], pub proof_b:[u8;128], pub proof_c:[u8;64], pub public:&'static[[u8;32]],\n}\n\n";
out += BORROW_BLOCK + "\n";
out += LOCK_BLOCK + "\n";
out += UNLOCK_BLOCK + "\n";
out += SEIZE_BLOCK + "\n";
out += RELEASE_REPAID_BLOCK + "\n";

fs.writeFileSync(fixturesPath, out);
console.log("wrote contracts/veil-verifier/src/fixtures.rs");
console.log("  BORROW  -> preserved verbatim");
console.log("  LOCK    -> regenerated from keys/lock.vk.json + /tmp/lock_{proof,public}.json");
console.log("  UNLOCK  -> preserved verbatim");
console.log("  SEIZE   -> preserved verbatim");
console.log("  RELEASE_REPAID -> regenerated from keys/release_repaid.vk.json + /tmp/release_repaid_{proof,public}.json");
