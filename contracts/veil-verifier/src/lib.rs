#![no_std]

//! Veil v3 Groth16 verifier for Circom/BN254 proofs on Soroban — mirrored from Nethermind
//! stellar-private-payments `circom-groth16-verifier` (Apache-2.0), which uses the native BN254
//! precompile (`soroban_sdk::crypto::bn254`, Protocol 26). No hand-rolled pairing math.
//!
//! One verifier build per circuit: the verification key is embedded at compile time by `build.rs`
//! from a snarkjs `verification_key.json`:
//!
//! ```bash
//! VERIFIER_VK_JSON=circom/keys/borrow.vk.json \
//!   cargo build -p veil-verifier --release --target wasm32v1-none
//! ```
//!
//! With `VERIFIER_VK_JSON` unset, `build.rs` emits a zero placeholder key so the crate still
//! compiles for `cargo check`/tests (which exercise the runtime `verify_with_vk` path instead).

extern crate alloc;

mod types;
pub use types::{Groth16Error, Groth16Proof, VerificationKeyBytes};

use soroban_sdk::{
    contract, contractimpl,
    crypto::bn254::{Bn254Fr, Bn254G1Affine as G1Affine, Bn254G2Affine as G2Affine},
    vec, BytesN, Env, Vec,
};

// Compile-time VK constants generated by build.rs from VERIFIER_VK_JSON.
include!(concat!(env!("OUT_DIR"), "/vk.rs"));

/// Groth16 verification key for BN254 (point form, reconstructed from the embedded bytes).
#[derive(Clone)]
pub struct VerificationKey {
    pub alpha: G1Affine,
    pub beta: G2Affine,
    pub gamma: G2Affine,
    pub delta: G2Affine,
    pub ic: Vec<G1Affine>,
}

/// Reconstruct a [`VerificationKey`] from byte form (used by tests via `verify_with_vk`).
#[cfg(test)]
pub(crate) fn verification_key_from_bytes(env: &Env, vk: &VerificationKeyBytes) -> VerificationKey {
    let mut ic: Vec<G1Affine> = Vec::new(env);
    for bytes in vk.ic.iter() {
        ic.push_back(G1Affine::from_bytes(bytes));
    }
    VerificationKey {
        alpha: G1Affine::from_bytes(vk.alpha.clone()),
        beta: G2Affine::from_bytes(vk.beta.clone()),
        gamma: G2Affine::from_bytes(vk.gamma.clone()),
        delta: G2Affine::from_bytes(vk.delta.clone()),
        ic,
    }
}

fn embedded_vk(env: &Env) -> VerificationKey {
    let mut ic: Vec<G1Affine> = Vec::new(env);
    for bytes in VK_IC.iter() {
        ic.push_back(G1Affine::from_bytes(BytesN::from_array(env, bytes)));
    }
    VerificationKey {
        alpha: G1Affine::from_bytes(BytesN::from_array(env, &VK_ALPHA_G1)),
        beta: G2Affine::from_bytes(BytesN::from_array(env, &VK_BETA_G2)),
        gamma: G2Affine::from_bytes(BytesN::from_array(env, &VK_GAMMA_G2)),
        delta: G2Affine::from_bytes(BytesN::from_array(env, &VK_DELTA_G2)),
        ic,
    }
}

/// Groth16 verifier for BN254/Circom proofs (embedded per-circuit verification key).
#[contract]
pub struct VeilVerifier;

#[contractimpl]
impl VeilVerifier {
    /// Verify a Groth16 proof against the compile-time embedded verification key. No storage is
    /// read or written — the key is part of the contract WASM. `public_inputs` must be the circuit's
    /// public signals in snarkjs order (circuit OUTPUTS first, then declared public inputs).
    pub fn verify(
        env: Env,
        proof: Groth16Proof,
        public_inputs: Vec<Bn254Fr>,
    ) -> Result<bool, Groth16Error> {
        let vk = embedded_vk(&env);
        Self::verify_with_vk(&env, &vk, proof, public_inputs)
    }

    /// The pairing check `e(-A, B) · e(alpha, beta) · e(vk_x, gamma) · e(C, delta) == 1`, where
    /// `vk_x = IC[0] + Σ public_inputs[i]·IC[i+1]`. `pub(crate)` (not exported as a contract fn — it
    /// takes a non-Soroban `VerificationKey`); `verify` calls it with the embedded key, tests with any.
    pub(crate) fn verify_with_vk(
        env: &Env,
        vk: &VerificationKey,
        proof: Groth16Proof,
        pub_inputs: Vec<Bn254Fr>,
    ) -> Result<bool, Groth16Error> {
        let bn = env.crypto().bn254();

        // IC must have exactly one commitment per public input, plus the constant term IC[0].
        if pub_inputs.len().checked_add(1) != Some(vk.ic.len()) {
            return Err(Groth16Error::MalformedPublicInputs);
        }

        let mut vk_x = vk.ic.get(0).ok_or(Groth16Error::MalformedPublicInputs)?;
        for i in 0..pub_inputs.len() {
            let s = pub_inputs.get(i).ok_or(Groth16Error::MalformedPublicInputs)?;
            let ic_idx = i.checked_add(1).ok_or(Groth16Error::MalformedPublicInputs)?;
            let v = vk.ic.get(ic_idx).ok_or(Groth16Error::MalformedPublicInputs)?;
            let prod = bn.g1_mul(&v, &s);
            vk_x = bn.g1_add(&vk_x, &prod);
        }

        #[allow(clippy::arithmetic_side_effects)]
        let neg_a = -proof.a;
        let g1_points = vec![env, neg_a, vk.alpha.clone(), vk_x, proof.c];
        let g2_points = vec![env, proof.b, vk.beta.clone(), vk.gamma.clone(), vk.delta.clone()];

        if bn.pairing_check(g1_points, g2_points) {
            Ok(true)
        } else {
            Err(Groth16Error::InvalidProof)
        }
    }
}

